// scripts/printRoutes.ts
// Prints every mounted route as markdown. `npm run routes > docs/routes.md`.
import createApp from '../src/app.js';

process.env.NODE_ENV = 'test';
process.env.JWT_SECRET ||= 'x';
process.env.JWT_REFRESH_SECRET ||= 'y';

type Layer = { route?: { path: string; methods: Record<string, boolean>; stack: Array<{ name: string }> }; name: string; handle?: { stack?: Layer[] } };

const app = await createApp();
const rows: Array<{ method: string; path: string; auth: boolean }> = [];
const walk = (stack: Layer[]) => {
  for (const layer of stack) {
    if (layer.route) {
      const auth = layer.route.stack.some(h => h.name === 'authMiddleware');
      for (const m of Object.keys(layer.route.methods)) rows.push({ method: m.toUpperCase(), path: layer.route.path, auth });
    } else if (layer.name === 'router' && layer.handle?.stack) {
      walk(layer.handle.stack);
    }
  }
};
walk(((app as unknown) as { router: { stack: Layer[] } }).router.stack);
rows.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));

const group = (p: string) => p.split('/')[1] || '/';
let current = '';
console.log('# API routes\n\nGenerated by `npm run routes`. Auth = requires `Authorization: Bearer <access token>`.\n');
for (const r of rows) {
  const g = group(r.path);
  if (g !== current) { current = g; console.log(`\n## /${g}\n\n| Method | Path | Auth |\n|---|---|---|`); }
  console.log(`| ${r.method} | \`${r.path}\` | ${r.auth ? 'yes' : 'no'} |`);
}
process.exit(0);
